#!/usr/bin/env python3
"""Generate tak_mesh_bridge.dart — bidirectional Meshtastic-TAK bridge."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/tak_mesh_bridge.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:async';")
a("import 'dart:typed_data';")
a("")
a("import '../../core/logging.dart';")
a("import '../../generated/meshtastic/atak.pb.dart';")
a("import 'cot_compressor.dart';")
a("import 'cot_serializer.dart';")
a("import 'tak_server.dart';")
a("")
a("/// Direction of bridge traffic for monitoring.")
a("enum TakBridgeDirection {")
a("  /// Meshtastic mesh -> TAK client.")
a("  meshToTak,")
a("")
a("  /// TAK client -> Meshtastic mesh.")
a("  takToMesh,")
a("}")
a("")
a("/// A bridge event for monitoring and statistics.")
a("class TakBridgeEvent {")
a("  final TakBridgeDirection direction;")
a("  final int payloadBytes;")
a("  final DateTime timestamp;")
a("  final String? error;")
a("")
a("  TakBridgeEvent({")
a("    required this.direction,")
a("    required this.payloadBytes,")
a("    DateTime? timestamp,")
a("    this.error,")
a("  }) : timestamp = timestamp ?? DateTime.now();")
a("}")
a("")
a("/// Callback for sending a TAKPacket to the Meshtastic mesh.")
a("typedef MeshSendCallback = Future<void> Function(")
a("  Uint8List payload, {")
a("  required int portnum,")
a("  int? destination,")
a("});")
a("")
a("/// Bidirectional bridge between Meshtastic mesh and TAK clients.")
a("///")
a("/// Inbound: ATAK_PLUGIN packets from mesh -> CoT XML -> TAK clients.")
a("/// Outbound: CoT from TAK clients -> TAKPacket proto -> mesh.")
a("class TakMeshBridge {")
a("  /// Maximum mesh payload size.")
a("  static const int maxMeshPayload = 237;")
a("")
a("  /// ATAK_PLUGIN port number.")
a("  static const int atakPortnum = 72;")
a("")
a("  /// Minimum interval between outbound mesh packets per TAK client UID.")
a("  static const Duration outboundRateLimit = Duration(seconds: 5);")
a("")
a("  /// Maximum outbound mesh packets per minute (aggregate).")
a("  static const int maxOutboundPerMinute = 4;")
a("")
a("  /// Duplicate suppression window.")
a("  static const Duration dedupeWindow = Duration(seconds: 30);")
a("")
a("  /// Default stale time for position CoT events.")
a("  static const Duration positionStaleTime = Duration(minutes: 5);")
a("")
a("  final TakServer _server;")
a("  final MeshSendCallback _meshSend;")
a("  final _eventController = StreamController<TakBridgeEvent>.broadcast();")
a("  final _recentHashes = <int, DateTime>{};")
a("  final _lastOutboundByUid = <String, DateTime>{};")
a("  final _outboundTimestamps = <DateTime>[];")
a("  StreamSubscription<TakServerEvent>? _serverSubscription;")
a("  bool _running = false;")
a("")
a("  int _packetsInbound = 0;")
a("  int _packetsOutbound = 0;")
a("")
a("  TakMeshBridge({required TakServer server, required MeshSendCallback meshSend})")
a("      : _server = server,")
a("        _meshSend = meshSend;")
a("")
a("  /// Stream of bridge events for monitoring.")
a("  Stream<TakBridgeEvent> get events => _eventController.stream;")
a("")
a("  /// Whether the bridge is running.")
a("  bool get isRunning => _running;")
a("")
a("  /// Total inbound packets processed.")
a("  int get packetsInbound => _packetsInbound;")
a("")
a("  /// Total outbound packets sent.")
a("  int get packetsOutbound => _packetsOutbound;")
a("")
a("  /// Starts the bridge. Subscribes to server events for outbound path.")
a("  void start() {")
a("    if (_running) return;")
a("    _running = true;")
a("")
a("    _serverSubscription = _server.events.listen((event) {")
a("      if (event is TakCotReceived) {")
a("        _handleOutbound(event);")
a("      }")
a("    });")
a("")
a("    AppLogging.tak('Bridge started');")
a("  }")
a("")
a("  /// Stops the bridge.")
a("  void stop() {")
a("    if (!_running) return;")
a("    _running = false;")
a("    _serverSubscription?.cancel();")
a("    _serverSubscription = null;")
a("    AppLogging.tak('Bridge stopped');")
a("  }")
a("")
a("  /// Handles an inbound ATAK_PLUGIN packet from the mesh.")
a("  ///")
a("  /// Called by the ProtocolService when a packet with portnum 72 arrives.")
a("  void handleMeshPacket({")
a("    required Uint8List payload,")
a("    required int fromNodeNum,")
a("    required String callsign,")
a("  }) {")
a("    if (!_running) return;")
a("")
a("    // Duplicate suppression.")
a("    final hash = _hashPayload(payload);")
a("    _cleanExpiredHashes();")
a("    if (_recentHashes.containsKey(hash)) {")
a("      AppLogging.tak(")
a("        'Bridge: duplicate ATAK_PLUGIN packet from 0x${fromNodeNum.toRadixString(16).toUpperCase()}, suppressed',")
a("      );")
a("      return;")
a("    }")
a("    _recentHashes[hash] = DateTime.now();")
a("")
a("    // Parse TAKPacket.")
a("    TAKPacket packet;")
a("    try {")
a("      packet = TAKPacket.fromBuffer(payload);")
a("    } on Exception catch (e) {")
a("      AppLogging.tak('Bridge: failed to parse ATAK_PLUGIN packet: $e');")
a("      _emitEvent(TakBridgeDirection.meshToTak, payload.length, error: e.toString());")
a("      return;")
a("    }")
a("")
a("    // Decompress if needed.")
a("    if (packet.isCompressed && packet.whichPayloadVariant() == TAKPacket_PayloadVariant.detail) {")
a("      try {")
a("        final decompressed = CotCompressor.decompress(Uint8List.fromList(packet.detail));")
a("        packet.detail = decompressed;")
a("        packet.isCompressed = false;")
a("      } on Exception catch (e) {")
a("        AppLogging.tak('Bridge: decompression failed: $e');")
a("      }")
a("    }")
a("")
a("    // Convert to CoT XML.")
a("    final cotXml = CotSerializer.takPacketToCotXml(")
a("      packet,")
a("      nodeNum: fromNodeNum,")
a("      callsign: callsign,")
a("    );")
a("")
a("    // Broadcast to all TAK clients.")
a("    _server.broadcastCot(cotXml);")
a("")
a("    final variant = packet.whichPayloadVariant().name;")
a("    AppLogging.tak(")
a("      'Bridge: mesh->TAK ATAK_PLUGIN packet from 0x${fromNodeNum.toRadixString(16).toUpperCase()} ($variant, ${payload.length} bytes)',")
a("    );")
a("    AppLogging.tak(")
a("      'Bridge: converted to CoT XML, broadcast to ${_server.clientCount} TAK clients',")
a("    );")
a("")
a("    _packetsInbound++;")
a("    _emitEvent(TakBridgeDirection.meshToTak, payload.length);")
a("  }")
a("")
a("  /// Disposes the bridge and releases resources.")
a("  Future<void> dispose() async {")
a("    stop();")
a("    await _eventController.close();")
a("  }")
a("")
a("  // --- Outbound: TAK -> Mesh ---")
a("")
a("  void _handleOutbound(TakCotReceived event) {")
a("    final session = event.session;")
a("    final uid = session.uid.isNotEmpty ? session.uid : session.remoteAddress;")
a("")
a("    // Per-client rate limiting.")
a("    final lastSend = _lastOutboundByUid[uid];")
a("    if (lastSend != null && DateTime.now().difference(lastSend) < outboundRateLimit) {")
a("      AppLogging.tak(")
a("        'Bridge: TAK->mesh rate-limited $uid (last send ${DateTime.now().difference(lastSend).inSeconds}s ago)',")
a("      );")
a("      return;")
a("    }")
a("")
a("    // Aggregate rate limiting.")
a("    _cleanOutboundTimestamps();")
a("    if (_outboundTimestamps.length >= maxOutboundPerMinute) {")
a("      AppLogging.tak(")
a("        'Bridge: TAK->mesh aggregate rate limit reached ($maxOutboundPerMinute/min)',")
a("      );")
a("      return;")
a("    }")
a("")
a("    // Parse CoT XML to TAKPacket.")
a("    TAKPacket packet;")
a("    try {")
a("      packet = CotSerializer.cotXmlToTakPacket(event.cotXml);")
a("    } on Exception catch (e) {")
a("      AppLogging.tak('Bridge: failed to parse CoT XML: $e');")
a("      return;")
a("    }")
a("")
a("    // Serialize to protobuf.")
a("    var meshPayload = Uint8List.fromList(packet.writeToBuffer());")
a("")
a("    // Try compression if payload is large.")
a("    if (meshPayload.length > CotCompressor.compressionThreshold) {")
a("      final compressed = CotCompressor.compress(meshPayload);")
a("      if (compressed != null) {")
a("        packet.isCompressed = true;")
a("        meshPayload = Uint8List.fromList(packet.writeToBuffer());")
a("      }")
a("    }")
a("")
a("    // Size validation.")
a("    if (meshPayload.length > maxMeshPayload) {")
a("      AppLogging.tak(")
a("        'Bridge: TAK->mesh CoT rejected: payload ${meshPayload.length} bytes exceeds $maxMeshPayload byte mesh limit',")
a("      );")
a("      _emitEvent(TakBridgeDirection.takToMesh, meshPayload.length, error: 'oversized');")
a("      return;")
a("    }")
a("")
a("    // Send to mesh.")
a("    final callsign = session.callsign.isNotEmpty ? session.callsign : uid;")
a("    AppLogging.tak(")
a("      'Bridge: TAK->mesh CoT from $callsign (${meshPayload.length} bytes), sending on portnum $atakPortnum',")
a("    );")
a("")
a("    _meshSend(meshPayload, portnum: atakPortnum);")
a("    _lastOutboundByUid[uid] = DateTime.now();")
a("    _outboundTimestamps.add(DateTime.now());")
a("    _packetsOutbound++;")
a("    _emitEvent(TakBridgeDirection.takToMesh, meshPayload.length);")
a("  }")
a("")
a("  // --- Helpers ---")
a("")
a("  int _hashPayload(Uint8List data) {")
a("    // Simple hash for dedup (not cryptographic).")
a("    var hash = 0x811c9dc5;")
a("    for (final b in data) {")
a("      hash ^= b;")
a("      hash = (hash * 0x01000193) & 0xFFFFFFFF;")
a("    }")
a("    return hash;")
a("  }")
a("")
a("  void _cleanExpiredHashes() {")
a("    final cutoff = DateTime.now().subtract(dedupeWindow);")
a("    _recentHashes.removeWhere((_, ts) => ts.isBefore(cutoff));")
a("  }")
a("")
a("  void _cleanOutboundTimestamps() {")
a("    final cutoff = DateTime.now().subtract(const Duration(minutes: 1));")
a("    _outboundTimestamps.removeWhere((ts) => ts.isBefore(cutoff));")
a("  }")
a("")
a("  void _emitEvent(TakBridgeDirection direction, int bytes, {String? error}) {")
a("    _eventController.add(TakBridgeEvent(")
a("      direction: direction,")
a("      payloadBytes: bytes,")
a("      error: error,")
a("    ));")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
