#!/usr/bin/env python3
"""Generate tak_server.dart."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/tak_server.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:async';")
a("import 'dart:io';")
a("")
a("import '../../core/logging.dart';")
a("import 'certificate_manager.dart';")
a("import 'tak_client_session.dart';")
a("")
a("/// Events emitted by [TakServer].")
a("sealed class TakServerEvent {")
a("  const TakServerEvent();")
a("}")
a("")
a("/// A client connected to the server.")
a("class TakClientConnected extends TakServerEvent {")
a("  final TakClientSession session;")
a("  const TakClientConnected(this.session);")
a("}")
a("")
a("/// A client disconnected from the server.")
a("class TakClientDisconnected extends TakServerEvent {")
a("  final TakClientSession session;")
a("  const TakClientDisconnected(this.session);")
a("}")
a("")
a("/// A CoT event was received from a TAK client.")
a("class TakCotReceived extends TakServerEvent {")
a("  final TakClientSession session;")
a("  final String cotXml;")
a("  const TakCotReceived(this.session, this.cotXml);")
a("}")
a("")
a("/// A server error occurred.")
a("class TakServerError extends TakServerEvent {")
a("  final String message;")
a("  const TakServerError(this.message);")
a("}")
a("")
a("/// On-device TAK TCP/TLS server that accepts ATAK/iTAK client connections.")
a("///")
a("/// Uses mTLS with certificates from [TakCertificateManager].")
a("/// Manages connected client sessions and broadcasts CoT events.")
a("class TakServer {")
a("  /// Default server port (ATAK standard).")
a("  static const int defaultPort = 8089;")
a("")
a("  /// Maximum concurrent client connections.")
a("  static const int maxClients = 5;")
a("")
a("  /// Inactivity timeout before closing a session.")
a("  static const Duration inactivityTimeout = Duration(seconds: 120);")
a("")
a("  final TakCertificateManager _certManager;")
a("  final _eventController = StreamController<TakServerEvent>.broadcast();")
a("  final List<TakClientSession> _clients = [];")
a("  SecureServerSocket? _serverSocket;")
a("  Timer? _inactivityTimer;")
a("  bool _running = false;")
a("")
a("  TakServer(this._certManager);")
a("")
a("  /// Stream of server events.")
a("  Stream<TakServerEvent> get events => _eventController.stream;")
a("")
a("  /// Whether the server is running.")
a("  bool get isRunning => _running;")
a("")
a("  /// Current number of connected clients.")
a("  int get clientCount => _clients.length;")
a("")
a("  /// Connected client sessions (read-only view).")
a("  List<TakClientSession> get clients => List.unmodifiable(_clients);")
a("")
a("  /// Starts the TLS server on [port].")
a("  Future<void> start({int port = defaultPort}) async {")
a("    if (_running) return;")
a("")
a("    try {")
a("      final context = await _createSecurityContext();")
a("      _serverSocket = await SecureServerSocket.bind(")
a("        InternetAddress.anyIPv4,")
a("        port,")
a("        context,")
a("      );")
a("      _running = true;")
a("")
a("      AppLogging.tak('Server listening on 0.0.0.0:$port');")
a("")
a("      _serverSocket!.listen(")
a("        _onClientConnected,")
a("        onError: (Object error) {")
a("          AppLogging.tak('Server error: $error');")
a("          _eventController.add(TakServerError(error.toString()));")
a("        },")
a("      );")
a("")
a("      _inactivityTimer = Timer.periodic(")
a("        const Duration(seconds: 30),")
a("        (_) => _checkInactivity(),")
a("      );")
a("    } on SocketException catch (e) {")
a("      AppLogging.tak('Server failed to bind port $port: $e');")
a("      _eventController.add(TakServerError(e.toString()));")
a("    }")
a("  }")
a("")
a("  /// Stops the server and disconnects all clients.")
a("  Future<void> stop() async {")
a("    if (!_running) return;")
a("    _running = false;")
a("    _inactivityTimer?.cancel();")
a("")
a("    for (final client in List.of(_clients)) {")
a("      client.close();")
a("    }")
a("    _clients.clear();")
a("")
a("    await _serverSocket?.close();")
a("    _serverSocket = null;")
a("")
a("    AppLogging.tak('Server stopped');")
a("  }")
a("")
a("  /// Broadcasts a CoT XML event to all connected and authenticated clients.")
a("  void broadcastCot(String cotXml) {")
a("    for (final client in _clients) {")
a("      if (client.state == TakSessionState.authenticated) {")
a("        client.sendCot(cotXml);")
a("      }")
a("    }")
a("  }")
a("")
a("  /// Sends a CoT event to a specific client by callsign.")
a("  void sendToClient(String callsign, String cotXml) {")
a("    for (final client in _clients) {")
a("      if (client.callsign == callsign &&")
a("          client.state == TakSessionState.authenticated) {")
a("        client.sendCot(cotXml);")
a("        return;")
a("      }")
a("    }")
a("  }")
a("")
a("  /// Disposes the server and releases resources.")
a("  Future<void> dispose() async {")
a("    await stop();")
a("    await _eventController.close();")
a("  }")
a("")
a("  void _onClientConnected(SecureSocket socket) {")
a("    if (_clients.length >= maxClients) {")
a("      AppLogging.tak(")
a("        'Client rejected: max $maxClients connections reached',")
a("      );")
a("      socket.destroy();")
a("      return;")
a("    }")
a("")
a("    final session = TakClientSession(socket);")
a("    _clients.add(session);")
a("    _eventController.add(TakClientConnected(session));")
a("")
a("    // Listen for CoT events from this client.")
a("    session.cotEvents.listen((cotXml) {")
a("      _eventController.add(TakCotReceived(session, cotXml));")
a("    });")
a("")
a("    // Listen for session lifecycle events.")
a("    session.events.listen((event) {")
a("      if (event == TakSessionEvent.disconnected) {")
a("        _clients.remove(session);")
a("        _eventController.add(TakClientDisconnected(session));")
a("      }")
a("    });")
a("")
a("    session.start();")
a("  }")
a("")
a("  void _checkInactivity() {")
a("    final now = DateTime.now();")
a("    for (final client in List.of(_clients)) {")
a("      if (now.difference(client.lastActivityAt) > inactivityTimeout) {")
a("        AppLogging.tak(")
a("          'Client ${client.callsign.isNotEmpty ? client.callsign : client.remoteAddress} timed out (inactive ${inactivityTimeout.inSeconds}s)',")
a("        );")
a("        client.close();")
a("      }")
a("    }")
a("  }")
a("")
a("  Future<SecurityContext> _createSecurityContext() async {")
a("    final caPem = await _certManager.getCaCertificatePem();")
a("    final serverResult = await _certManager.getServerCertificateAndKey();")
a("")
a("    final context = SecurityContext()")
a("      ..useCertificateChainBytes(serverResult.certPem.codeUnits)")
a("      ..usePrivateKeyBytes(serverResult.keyPem.codeUnits)")
a("      ..setTrustedCertificatesBytes(caPem.codeUnits)")
a("      ..setClientAuthoritiesBytes(caPem.codeUnits);")
a("")
a("    return context;")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
