a("  /// Maximum outbound messages per rate-limit window per client.")
a("  static const int maxOutboundPerWindow = 2;")
a("")
a("  /// Rate-limit window duration.")
a("  static const Duration rateLimitWindow = Duration(seconds: 10);")
a("")
a("  /// TTL for pending receipt tracking.")
a("  static const Duration receiptTtl = Duration(minutes: 5);")
a("")
a("  final MeshTextSendCallback _meshSend;")
