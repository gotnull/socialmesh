a("")
a("      // Parse UID: GeoChat.{senderUid}.{recipientUid}.{messageId}")
a("      final parts = uid.split('.');")
a("      final senderUid = parts.length > 1 ? parts[1] : uid;")
a("      final recipientUid = parts.length > 2 ? parts[2] : null;")
a("      final messageId = parts.length > 3 ? parts[3] : uid;")
a("")
a("      return GeoChatMessage(")
a("        senderUid: senderUid,")
a("        senderCallsign: senderCallsign,")
a("        text: text,")
a("        messageId: messageId,")
a("        recipientUid: recipientUid,")
a("      );")
