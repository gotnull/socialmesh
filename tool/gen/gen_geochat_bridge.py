a("")
a("  /// Pending receipts: meshMessageId -> GeoChatSendResult.")
a("  final _pendingReceipts = <int, GeoChatSendResult>{};")
a("")
a("  /// Rate limiter: clientUid -> list of send timestamps.")
a("  final _rateLimits = <String, List<DateTime>>{};")
a("")
a("  GeoChatBridge({")
a("    required MeshTextSendCallback meshSend,")
a("    CallsignResolver? callsignResolver,")
a("  })  : _meshSend = meshSend,")
a("        _callsignResolver = callsignResolver;")
a("")
a("  /// Parses a GeoChat CoT XML event.")
a("  ///")
a("  /// Returns null if the XML is not a valid GeoChat event.")
a("  static GeoChatMessage? parseGeoChatCot(String cotXml) {")
a("    try {")
a("      final doc = XmlDocument.parse(cotXml);")
a("      final event = doc.rootElement;")
a("")
a("      // GeoChat type is b-t-f.")
a("      final type = event.getAttribute('type') ?? '';")
a("      if (!type.startsWith('b-t-f')) return null;")
a("")
a("      final uid = event.getAttribute('uid') ?? '';")
a("      final detail = event.findElements('detail').firstOrNull;")
a("      if (detail == null) return null;")
a("")
a("      // Extract chat element.")
a("      final chat = detail.findElements('__chat').firstOrNull;")
a("      final senderCallsign = chat?.getAttribute('senderCallsign') ?? '';")
a("")
a("      // Extract message text from remarks.")
a("      final remarks = detail.findElements('remarks').firstOrNull;")
