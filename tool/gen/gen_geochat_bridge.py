a("      builder.attribute('type', 'b-t-f');")
a("      builder.attribute('uid', chatUid);")
a("      builder.attribute('how', 'h-g-i-g-o');")
a("      builder.attribute('time', now);")
a("      builder.attribute('start', now);")
a("      builder.attribute('stale', stale);")
a("      builder.element('point', nest: () {")
a("        builder.attribute('lat', '0.0');")
a("        builder.attribute('lon', '0.0');")
a("        builder.attribute('hae', '0.0');")
a("        builder.attribute('ce', '9999999');")
a("        builder.attribute('le', '9999999');")
a("      });")
a("      builder.element('detail', nest: () {")
a("        builder.element('__chat', nest: () {")
a("          builder.attribute('senderCallsign', callsign);")
a("          builder.attribute('chatroom', recipientUid);")
a("          builder.attribute('id', chatUid);")
a("          builder.attribute('parent', 'RootContactGroup');")
a("          builder.element('chatgrp', nest: () {")
a("            builder.attribute('uid0', senderUid);")
a("            builder.attribute('uid1', recipientUid);")
a("            builder.attribute('id', chatUid);")
a("          });")
a("        });")
a("        builder.element('remarks', nest: () {")
a("          builder.attribute('source', senderUid);")
a("          builder.attribute('time', now);")
a("          builder.attribute('to', recipientUid);")
a("          builder.text(text);")
a("        });")
a("        builder.element('link', nest: () {")
a("          builder.attribute('uid', senderUid);")
a("          builder.attribute('type', 'a-f-G-U-C');")
