a("    final senderUid = 'MESHTASTIC-$nodeHex';")
a("    final recipientUid = toUid ?? 'All Chat Rooms';")
a("    final messageId = DateTime.now().millisecondsSinceEpoch.toRadixString(16);")
a("    final chatUid = 'GeoChat.$senderUid.$recipientUid.$messageId';")
a("    final now = DateTime.now().toUtc().toIso8601String();")
a("    final stale = DateTime.now().toUtc().add(const Duration(minutes: 5)).toIso8601String();")
a("")
