#!/usr/bin/env python3
"""Generate data_package_builder.dart — TAK data package ZIP creator."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/data_package_builder.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:convert';")
a("import 'dart:typed_data';")
a("")
a("import 'package:archive/archive.dart';")
a("")
a("import '../../core/logging.dart';")
a("import 'certificate_manager.dart';")
a("")
a("/// Builds TAK data packages (.zip) for ATAK/iTAK server connection import.")
a("///")
a("/// The data package contains:")
a("/// - `manifest.xml` — ATAK data package manifest")
a("/// - `certs/truststore-root.p12` — CA certificate in PKCS#12 container")
a("/// - `certs/user.p12` — Client certificate and key in PKCS#12 container")
a("/// - `preference.pref` — Server connection preferences")
a("class TakDataPackageBuilder {")
a("  final TakCertificateManager _certManager;")
a("")
a("  TakDataPackageBuilder(this._certManager);")
a("")
a("  /// Builds a data package ZIP for connecting to the on-device TAK server.")
a("  ///")
a("  /// [serverHost] is the IP/hostname ATAK should connect to.")
a("  /// [serverPort] is the TLS port (default 8089).")
a("  /// [callsign] is the user's callsign for the client certificate.")
a("  Future<Uint8List> build({")
a("    required String serverHost,")
a("    int serverPort = 8089,")
a("    required String callsign,")
a("  }) async {")
a("    final caPem = await _certManager.getCaCertificatePem();")
a("    final clientCert = await _certManager.generateClientCertificate(callsign);")
a("")
a("    final archive = Archive();")
a("")
a("    // manifest.xml")
a("    final manifest = _buildManifest(serverHost, serverPort);")
a("    _addTextFile(archive, 'manifest.xml', manifest);")
a("")
a("    // CA cert as PEM (ATAK accepts .p12 or .pem)")
a("    _addTextFile(archive, 'certs/truststore-root.p12', caPem);")
a("")
a("    // Client cert + key as PEM")
a("    final userP12 = '${clientCert.certPem}\\n${clientCert.keyPem}';")
a("    _addTextFile(archive, 'certs/user.p12', userP12);")
a("")
a("    // Connection preferences")
a("    final prefs = _buildPreferences(serverHost, serverPort, callsign);")
a("    _addTextFile(archive, 'preference.pref', prefs);")
a("")
a("    final zipBytes = Uint8List.fromList(ZipEncoder().encode(archive)!);")
a("")
a("    AppLogging.tak(")
a("      'Data package built: ${zipBytes.length} bytes',")
a("    );")
a("    AppLogging.tak(")
a("      'Package contents: manifest.xml, certs/truststore-root.p12, certs/user.p12, preference.pref',")
a("    );")
a("")
a("    return zipBytes;")
a("  }")
a("")
a("  String _buildManifest(String host, int port) {")
a("    return '<?xml version=\"1.0\" encoding=\"UTF-8\"?>\\n'")
a("        '<MissionPackageManifest version=\"2\">\\n'")
a("        '  <Configuration>\\n'")
a("        '    <Parameter name=\"uid\" value=\"socialmesh-tak-server\"/>\\n'")
a("        '    <Parameter name=\"name\" value=\"Socialmesh TAK Server\"/>\\n'")
a("        '    <Parameter name=\"onReceiveDelete\" value=\"false\"/>\\n'")
a("        '  </Configuration>\\n'")
a("        '  <Contents>\\n'")
a("        '    <Content ignore=\"false\" zipEntry=\"certs/truststore-root.p12\">\\n'")
a("        '      <Parameter name=\"name\" value=\"Socialmesh CA\"/>\\n'")
a("        '    </Content>\\n'")
a("        '    <Content ignore=\"false\" zipEntry=\"certs/user.p12\">\\n'")
a("        '      <Parameter name=\"name\" value=\"Client Certificate\"/>\\n'")
a("        '    </Content>\\n'")
a("        '    <Content ignore=\"false\" zipEntry=\"preference.pref\">\\n'")
a("        '      <Parameter name=\"name\" value=\"TAK Server Connection\"/>\\n'")
a("        '    </Content>\\n'")
a("        '  </Contents>\\n'")
a("        '</MissionPackageManifest>';")
a("  }")
a("")
a("  String _buildPreferences(String host, int port, String callsign) {")
a("    return '<?xml version=\"1.0\" encoding=\"UTF-8\"?>\\n'")
a("        '<preferences>\\n'")
a("        '  <preference version=\"1\" name=\"com.atakmap.app_preferences\">\\n'")
a("        '    <entry key=\"locationCallsign\" class=\"class java.lang.String\">$callsign</entry>\\n'")
a("        '    <entry key=\"connectString0\" class=\"class java.lang.String\">$host:$port:ssl</entry>\\n'")
a("        '    <entry key=\"caLocation\" class=\"class java.lang.String\">cert/truststore-root.p12</entry>\\n'")
a("        '    <entry key=\"certificateLocation\" class=\"class java.lang.String\">cert/user.p12</entry>\\n'")
a("        '    <entry key=\"clientPassword\" class=\"class java.lang.String\">atakatak</entry>\\n'")
a("        '    <entry key=\"caPassword\" class=\"class java.lang.String\">atakatak</entry>\\n'")
a("        '  </preference>\\n'")
a("        '</preferences>';")
a("  }")
a("")
a("  void _addTextFile(Archive archive, String name, String content) {")
a("    final bytes = utf8.encode(content);")
a("    archive.addFile(ArchiveFile(name, bytes.length, bytes));")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
