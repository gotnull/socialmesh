#!/usr/bin/env python3
"""Generate cot_serializer.dart — TAKPacket <-> CoT XML conversion."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/cot_serializer.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'package:xml/xml.dart';")
a("")
a("import '../../core/logging.dart';")
a("import '../../generated/meshtastic/atak.pb.dart';")
a("import '../../generated/meshtastic/atak.pbenum.dart';")
a("import 'team_role_mapper.dart';")
a("")
a("/// Converts between Meshtastic [TAKPacket] protobufs and CoT XML strings.")
a("///")
a("/// Handles PLI (position), GeoChat (messaging), and Group/Contact/Status")
a("/// detail elements. This is the codec used by [TakMeshBridge] for")
a("/// bidirectional translation between mesh and TAK wire formats.")
a("abstract final class CotSerializer {")
a("  /// CoT type for friendly ground unit position.")
a("  static const String cotTypePli = 'a-f-G-U-C';")
a("")
a("  /// CoT type for chat message.")
a("  static const String cotTypeChat = 'b-t-f';")
a("")
a("  /// Default stale duration for position events.")
a("  static const Duration staleDuration = Duration(minutes: 5);")
a("")
a("  /// Multiplier to convert protobuf fixed-point lat/lon to degrees.")
a("  static const double _coordScale = 1e-7;")
a("")
a("  /// Converts a [TAKPacket] to CoT XML string.")
a("  ///")
a("  /// [nodeNum] is the originating Meshtastic node number.")
a("  /// [callsign] is the display name for this entity.")
a("  static String takPacketToCotXml(")
a("    TAKPacket packet, {")
a("    required int nodeNum,")
a("    required String callsign,")
a("  }) {")
a("    final uid = _meshUid(nodeNum);")
a("    final now = DateTime.now().toUtc();")
a("    final stale = now.add(staleDuration);")
a("")
a("    final variant = packet.whichPayloadVariant();")
a("    switch (variant) {")
a("      case TAKPacket_PayloadVariant.pli:")
a("        return _pliToCotXml(packet, uid, callsign, now, stale);")
a("      case TAKPacket_PayloadVariant.chat:")
a("        return _chatToCotXml(packet, uid, callsign, now, stale);")
a("      case TAKPacket_PayloadVariant.detail:")
a("      case TAKPacket_PayloadVariant.notSet:")
a("        return _genericToCotXml(packet, uid, callsign, now, stale);")
a("    }")
a("  }")
a("")
a("  /// Parses CoT XML into a [TAKPacket].")
a("  static TAKPacket cotXmlToTakPacket(String cotXml) {")
a("    final doc = XmlDocument.parse(cotXml);")
a("    final event = doc.rootElement;")
a("")
a("    final type = event.getAttribute('type') ?? '';")
a("    final detail = event.findElements('detail').firstOrNull;")
a("")
a("    final packet = TAKPacket();")
a("")
a("    // Parse contact.")
a("    final contactEl = detail?.findElements('contact').firstOrNull;")
a("    if (contactEl != null) {")
a("      packet.contact = Contact()")
a("        ..callsign = contactEl.getAttribute('callsign') ?? ''")
a("        ..deviceCallsign = contactEl.getAttribute('deviceCallsign') ?? '';")
a("    }")
a("")
a("    // Parse group.")
a("    final groupEl = detail?.findElements('__group').firstOrNull;")
a("    if (groupEl != null) {")
a("      final teamName = groupEl.getAttribute('name') ?? '';")
a("      final roleName = groupEl.getAttribute('role') ?? '';")
a("      packet.group = Group()")
a("        ..team = TeamRoleMapper.nameToTeam(teamName)")
a("        ..role = TeamRoleMapper.nameToRole(roleName);")
a("    }")
a("")
a("    // Parse status.")
a("    final statusEl = detail?.findElements('status').firstOrNull;")
a("    if (statusEl != null) {")
a("      final battery = int.tryParse(statusEl.getAttribute('battery') ?? '');")
a("      if (battery != null) {")
a("        packet.status = Status()..battery = battery;")
a("      }")
a("    }")
a("")
a("    // Determine payload variant from CoT type.")
a("    if (type == cotTypeChat || type.startsWith('b-t-f')) {")
a("      _parseChatPayload(packet, detail);")
a("    } else if (type.startsWith('a-')) {")
a("      _parsePliPayload(packet, event);")
a("    }")
a("")
a("    final payloadType = packet.whichPayloadVariant().name;")
a("    final size = packet.writeToBuffer().length;")
a("    AppLogging.tak(")
a("      'Deserialized CoT XML -> TAKPacket($payloadType) ($size bytes)',")
a("    );")
a("")
a("    return packet;")
a("  }")
a("")
a("  // --- Private helpers ---")
a("")
a("  static String _meshUid(int nodeNum) =>")
a("      'MESHTASTIC-${nodeNum.toRadixString(16).toUpperCase().padLeft(8, '0')}';")
a("")
a("  static String _isoTime(DateTime dt) => dt.toIso8601String();")
a("")
a("  static String _pliToCotXml(")
a("    TAKPacket packet,")
a("    String uid,")
a("    String callsign,")
a("    DateTime now,")
a("    DateTime stale,")
a("  ) {")
a("    final pli = packet.pli;")
a("    final lat = pli.latitudeI * _coordScale;")
a("    final lon = pli.longitudeI * _coordScale;")
a("    final hae = pli.altitude.toDouble();")
a("")
a("    final cotType = _buildCotType(packet);")
a("")
a("    final builder = XmlBuilder();")
a("    builder.element('event', attributes: {")
a("      'version': '2.0',")
a("      'uid': uid,")
a("      'type': cotType,")
a("      'time': _isoTime(now),")
a("      'start': _isoTime(now),")
a("      'stale': _isoTime(stale),")
a("      'how': 'h-g-i-g-o',")
a("    }, nest: () {")
a("      builder.element('point', attributes: {")
a("        'lat': lat.toStringAsFixed(7),")
a("        'lon': lon.toStringAsFixed(7),")
a("        'hae': hae.toStringAsFixed(1),")
a("        'ce': '9999999.0',")
a("        'le': '9999999.0',")
a("      });")
a("      builder.element('detail', nest: () {")
a("        _addContactElement(builder, packet, callsign);")
a("        _addGroupElement(builder, packet);")
a("        _addStatusElement(builder, packet);")
a("        if (pli.speed > 0 || pli.course > 0) {")
a("          builder.element('track', attributes: {")
a("            'speed': pli.speed.toString(),")
a("            'course': pli.course.toString(),")
a("          });")
a("        }")
a("      });")
a("    });")
a("")
a("    final xml = builder.buildDocument().toXmlString();")
a("    AppLogging.tak(")
a("      'Serialized TAKPacket(PLI) -> CoT XML: uid=$uid, type=$cotType (${xml.length} bytes)',")
a("    );")
a("    return xml;")
a("  }")
a("")
a("  static String _chatToCotXml(")
a("    TAKPacket packet,")
a("    String uid,")
a("    String callsign,")
a("    DateTime now,")
a("    DateTime stale,")
a("  ) {")
a("    final chat = packet.chat;")
a("    final chatUid = '$uid-chat-${now.millisecondsSinceEpoch}';")
a("")
a("    final builder = XmlBuilder();")
a("    builder.element('event', attributes: {")
a("      'version': '2.0',")
a("      'uid': chatUid,")
a("      'type': cotTypeChat,")
a("      'time': _isoTime(now),")
a("      'start': _isoTime(now),")
a("      'stale': _isoTime(stale),")
a("      'how': 'h-g-i-g-o',")
a("    }, nest: () {")
a("      builder.element('point', attributes: {")
a("        'lat': '0.0000000',")
a("        'lon': '0.0000000',")
a("        'hae': '0.0',")
a("        'ce': '9999999.0',")
a("        'le': '9999999.0',")
a("      });")
a("      builder.element('detail', nest: () {")
a("        _addContactElement(builder, packet, callsign);")
a("        builder.element('__chat', attributes: {")
a("          'senderCallsign': callsign,")
a("          'id': uid,")
a("          if (chat.to.isNotEmpty) 'to': chat.to,")
a("          if (chat.toCallsign.isNotEmpty) 'toCallsign': chat.toCallsign,")
a("        }, nest: () {")
a("          builder.element('chatgrp', attributes: {")
a("            'uid0': uid,")
a("            'uid1': chat.to.isNotEmpty ? chat.to : 'All Chat Rooms',")
a("          });")
a("        });")
a("        builder.element('remarks', nest: () {")
a("          builder.text(chat.message);")
a("        });")
a("      });")
a("    });")
a("")
a("    final xml = builder.buildDocument().toXmlString();")
a("    AppLogging.tak(")
a("      'Serialized TAKPacket(GeoChat) -> CoT XML: uid=$chatUid (${xml.length} bytes)',")
a("    );")
a("    return xml;")
a("  }")
a("")
a("  static String _genericToCotXml(")
a("    TAKPacket packet,")
a("    String uid,")
a("    String callsign,")
a("    DateTime now,")
a("    DateTime stale,")
a("  ) {")
a("    final builder = XmlBuilder();")
a("    builder.element('event', attributes: {")
a("      'version': '2.0',")
a("      'uid': uid,")
a("      'type': cotTypePli,")
a("      'time': _isoTime(now),")
a("      'start': _isoTime(now),")
a("      'stale': _isoTime(stale),")
a("      'how': 'h-g-i-g-o',")
a("    }, nest: () {")
a("      builder.element('point', attributes: {")
a("        'lat': '0.0000000',")
a("        'lon': '0.0000000',")
a("        'hae': '0.0',")
a("        'ce': '9999999.0',")
a("        'le': '9999999.0',")
a("      });")
a("      builder.element('detail', nest: () {")
a("        _addContactElement(builder, packet, callsign);")
a("        _addGroupElement(builder, packet);")
a("        _addStatusElement(builder, packet);")
a("      });")
a("    });")
a("")
a("    return builder.buildDocument().toXmlString();")
a("  }")
a("")
a("  static String _buildCotType(TAKPacket packet) {")
a("    if (packet.hasGroup()) {")
a("      final suffix = TeamRoleMapper.cotTypeSuffix(packet.group.role);")
a("      if (suffix.isNotEmpty) return 'a-f-G-U-C-$suffix';")
a("    }")
a("    return cotTypePli;")
a("  }")
a("")
a("  static void _addContactElement(")
a("    XmlBuilder builder,")
a("    TAKPacket packet,")
a("    String callsign,")
a("  ) {")
a("    final cs = packet.hasContact() && packet.contact.callsign.isNotEmpty")
a("        ? packet.contact.callsign")
a("        : callsign;")
a("    final deviceCs =")
a("        packet.hasContact() ? packet.contact.deviceCallsign : '';")
a("    builder.element('contact', attributes: {")
a("      'callsign': cs,")
a("      if (deviceCs.isNotEmpty) 'deviceCallsign': deviceCs,")
a("    });")
a("  }")
a("")
a("  static void _addGroupElement(XmlBuilder builder, TAKPacket packet) {")
a("    if (!packet.hasGroup()) return;")
a("    final attrs = TeamRoleMapper.groupToCoTAttributes(")
a("      packet.group.team,")
a("      packet.group.role,")
a("    );")
a("    builder.element('__group', attributes: {")
a("      'name': attrs['team']!,")
a("      'role': attrs['role']!,")
a("    });")
a("  }")
a("")
a("  static void _addStatusElement(XmlBuilder builder, TAKPacket packet) {")
a("    if (!packet.hasStatus()) return;")
a("    builder.element('status', attributes: {")
a("      'battery': packet.status.battery.toString(),")
a("    });")
a("  }")
a("")
a("  static void _parsePliPayload(TAKPacket packet, XmlElement event) {")
a("    final point = event.findElements('point').firstOrNull;")
a("    if (point == null) return;")
a("")
a("    final lat = double.tryParse(point.getAttribute('lat') ?? '') ?? 0;")
a("    final lon = double.tryParse(point.getAttribute('lon') ?? '') ?? 0;")
a("    final hae = double.tryParse(point.getAttribute('hae') ?? '') ?? 0;")
a("")
a("    final pli = PLI()")
a("      ..latitudeI = (lat / _coordScale).round()")
a("      ..longitudeI = (lon / _coordScale).round()")
a("      ..altitude = hae.round();")
a("")
a("    // Parse track element for speed/course.")
a("    final detail = event.findElements('detail').firstOrNull;")
a("    final track = detail?.findElements('track').firstOrNull;")
a("    if (track != null) {")
a("      pli.speed = int.tryParse(track.getAttribute('speed') ?? '') ?? 0;")
a("      pli.course = int.tryParse(track.getAttribute('course') ?? '') ?? 0;")
a("    }")
a("")
a("    packet.pli = pli;")
a("  }")
a("")
a("  static void _parseChatPayload(TAKPacket packet, XmlElement? detail) {")
a("    if (detail == null) return;")
a("")
a("    final chatEl = detail.findElements('__chat').firstOrNull;")
a("    final remarksEl = detail.findElements('remarks').firstOrNull;")
a("")
a("    final chat = GeoChat()")
a("      ..message = remarksEl?.innerText ?? ''")
a("      ..to = chatEl?.getAttribute('to') ?? ''")
a("      ..toCallsign = chatEl?.getAttribute('toCallsign') ?? '';")
a("")
a("    packet.chat = chat;")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
