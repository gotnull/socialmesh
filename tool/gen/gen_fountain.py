"""Generate fountain_codec.dart — LT fountain code for mesh fragmentation."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/fountain_codec.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:math';")
a("import 'dart:typed_data';")
a("")
a("import '../../core/logging.dart';")
a("")
a("/// Header prepended to each encoding symbol for reassembly.")
a("///")
a("/// Layout: messageId (4) + symbolIndex (2) + totalSourceSymbols (2) + seed (4) = 12 bytes.")
a("class FountainSymbolHeader {")
a("  final int messageId;")
a("  final int symbolIndex;")
a("  final int totalSourceSymbols;")
a("  final int seed;")
a("")
a("  const FountainSymbolHeader({")
a("    required this.messageId,")
a("    required this.symbolIndex,")
a("    required this.totalSourceSymbols,")
a("    required this.seed,")
a("  });")
a("")
a("  static const int headerSize = 12;")
a("")
a("  Uint8List encode() {")
a("    final bd = ByteData(headerSize);")
a("    bd.setUint32(0, messageId, Endian.big);")
a("    bd.setUint16(4, symbolIndex, Endian.big);")
a("    bd.setUint16(6, totalSourceSymbols, Endian.big);")
a("    bd.setUint32(8, seed, Endian.big);")
a("    return bd.buffer.asUint8List();")
a("  }")
a("")
a("  static FountainSymbolHeader decode(Uint8List data) {")
a("    final bd = ByteData.sublistView(data);")
a("    return FountainSymbolHeader(")
a("      messageId: bd.getUint32(0, Endian.big),")
a("      symbolIndex: bd.getUint16(4, Endian.big),")
a("      totalSourceSymbols: bd.getUint16(6, Endian.big),")
a("      seed: bd.getUint32(8, Endian.big),")
a("    );")
a("  }")
a("}")
a("")
a("/// A single encoding symbol: header + payload bytes.")
a("class FountainSymbol {")
a("  final FountainSymbolHeader header;")
a("  final Uint8List payload;")
a("")
a("  const FountainSymbol({required this.header, required this.payload});")
a("")
a("  Uint8List encode() {")
a("    final headerBytes = header.encode();")
a("    final result = Uint8List(headerBytes.length + payload.length);")
a("    result.setAll(0, headerBytes);")
a("    result.setAll(headerBytes.length, payload);")
a("    return result;")
a("  }")
a("")
a("  static FountainSymbol decode(Uint8List data) {")
a("    final header = FountainSymbolHeader.decode(data);")
a("    final payload = data.sublist(FountainSymbolHeader.headerSize);")
a("    return FountainSymbol(header: header, payload: Uint8List.fromList(payload));")
a("  }")
a("}")
a("")
a("/// Encodes payloads into fountain-coded symbols for reliable mesh delivery.")
a("///")
a("/// Uses systematic LT codes: first `k` symbols are raw source blocks,")
a("/// additional symbols are XOR combinations for redundancy.")
a("class FountainEncoder {")
a("  /// Default symbol payload size (bytes), leaving room for header in 237-byte packets.")
a("  static const int defaultSymbolSize = 200;")
a("")
a("  /// Default redundancy factor (1.5 = 50% extra symbols).")
a("  static const double defaultRedundancy = 1.5;")
a("")
a("  static final _rng = Random();")
a("")
a("  /// Encodes [payload] into a list of [FountainSymbol]s.")
a("  ///")
a("  /// Returns source symbols plus redundancy symbols. The receiver")
a("  /// needs any `k` symbols to reconstruct the original payload.")
a("  static List<FountainSymbol> encode(")
a("    Uint8List payload, {")
a("    int symbolSize = defaultSymbolSize,")
a("    double redundancy = defaultRedundancy,")
a("  }) {")
a("    final k = (payload.length / symbolSize).ceil();")
a("    final n = (k * redundancy).ceil();")
a("")
a("    // Pad payload to exact multiple of symbolSize.")
a("    final padded = Uint8List(k * symbolSize);")
a("    padded.setAll(0, payload);")
a("")
a("    // Split into source symbols.")
a("    final sourceSymbols = <Uint8List>[];")
a("    for (var i = 0; i < k; i++) {")
a("      sourceSymbols.add(padded.sublist(i * symbolSize, (i + 1) * symbolSize));")
a("    }")
a("")
a("    final messageId = _rng.nextInt(0xFFFFFFFF);")
a("")
a("    final result = <FountainSymbol>[];")
a("")
a("    // First k symbols are systematic (raw source blocks).")
a("    for (var i = 0; i < k; i++) {")
a("      result.add(FountainSymbol(")
a("        header: FountainSymbolHeader(")
a("          messageId: messageId,")
a("          symbolIndex: i,")
a("          totalSourceSymbols: k,")
a("          seed: 0, // seed=0 means systematic (direct source symbol)")
a("        ),")
a("        payload: sourceSymbols[i],")
a("      ));")
a("    }")
a("")
a("    // Additional symbols are XOR combinations.")
a("    for (var i = k; i < n; i++) {")
a("      final seed = _rng.nextInt(0xFFFFFFFF) | 1; // ensure non-zero")
a("      final degree = _degree(seed, k);")
a("      final indices = _selectIndices(seed, k, degree);")
a("      final xored = _xorSymbols(sourceSymbols, indices, symbolSize);")
a("")
a("      result.add(FountainSymbol(")
a("        header: FountainSymbolHeader(")
a("          messageId: messageId,")
a("          symbolIndex: i,")
a("          totalSourceSymbols: k,")
a("          seed: seed,")
a("        ),")
a("        payload: xored,")
a("      ));")
a("    }")
a("")
a("    AppLogging.tak(")
a("      'Fountain: encoding ${payload.length} byte payload -> $k source symbols, $n encoding symbols ($symbolSize byte symbols)',")
a("    );")
a("")
a("    return result;")
a("  }")
a("")
a("  /// Determines the degree (number of source symbols to XOR) from a seed.")
a("  static int _degree(int seed, int k) {")
a("    if (k <= 1) return 1;")
a("    // Simple degree distribution biased towards low degree for small k.")
a("    final r = Random(seed);")
a("    final d = r.nextInt(k) + 1;")
a("    // Bias towards degree 1-2 for better peeling decode.")
a("    return d <= 2 ? d : (r.nextBool() ? 2 : d);")
a("  }")
a("")
a("  /// Selects [degree] distinct source symbol indices using [seed].")
a("  static List<int> _selectIndices(int seed, int k, int degree) {")
a("    final r = Random(seed + 1);")
a("    final indices = <int>{};")
a("    while (indices.length < degree) {")
a("      indices.add(r.nextInt(k));")
a("    }")
a("    return indices.toList();")
a("  }")
a("")
a("  /// XORs the source symbols at [indices] together.")
a("  static Uint8List _xorSymbols(")
a("    List<Uint8List> sources,")
a("    List<int> indices,")
a("    int symbolSize,")
a("  ) {")
a("    final result = Uint8List(symbolSize);")
a("    for (final idx in indices) {")
a("      for (var b = 0; b < symbolSize; b++) {")
a("        result[b] ^= sources[idx][b];")
a("      }")
a("    }")
a("    return result;")
a("  }")
a("}")
a("")
a("/// Tracks state for a single in-progress fountain decode session.")
a("class _DecodeSession {")
a("  final int messageId;")
a("  final int k;")
a("  final int symbolSize;")
a("  final int originalPayloadLength;")
a("  final DateTime created;")
a("  final Map<int, Uint8List> receivedSource = {};")
a("  final List<FountainSymbol> paritySymbols = [];")
a("")
a("  _DecodeSession({")
a("    required this.messageId,")
a("    required this.k,")
a("    required this.symbolSize,")
a("    required this.originalPayloadLength,")
a("  }) : created = DateTime.now();")
a("}")
a("")
a("/// Decodes fountain-coded symbols back into the original payload.")
a("class FountainDecoder {")
a("  /// Decode timeout (discard incomplete sessions after this duration).")
a("  static const Duration timeout = Duration(seconds: 60);")
a("")
a("  /// Maximum concurrent decode sessions.")
a("  static const int maxSessions = 10;")
a("")
a("  final Map<int, _DecodeSession> _sessions = {};")
a("")
a("  /// Adds a received [symbol] to the decoder.")
a("  ///")
a("  /// Returns the decoded payload when enough symbols are received,")
a("  /// or `null` if more symbols are needed.")
a("  Uint8List? addSymbol(FountainSymbol symbol) {")
a("    _evictExpired();")
a("")
a("    final hdr = symbol.header;")
a("    final session = _sessions.putIfAbsent(")
a("      hdr.messageId,")
a("      () {")
a("        _evictOldestIfFull();")
a("        return _DecodeSession(")
a("          messageId: hdr.messageId,")
a("          k: hdr.totalSourceSymbols,")
a("          symbolSize: symbol.payload.length,")
a("          originalPayloadLength: 0,")
a("        );")
a("      },")
a("    );")
a("")
a("    // Systematic symbol (seed == 0): direct source block.")
a("    if (hdr.seed == 0 && hdr.symbolIndex < session.k) {")
a("      session.receivedSource[hdr.symbolIndex] = symbol.payload;")
a("    } else {")
a("      session.paritySymbols.add(symbol);")
a("    }")
a("")
a("    AppLogging.tak(")
a("      'Fountain: received symbol ${hdr.symbolIndex}/${session.k} for message ${hdr.messageId.toRadixString(16)} '")
a("      '(have ${session.receivedSource.length} source + ${session.paritySymbols.length} parity)',")
a("    );")
a("")
a("    // Try to decode.")
a("    final decoded = _tryDecode(session);")
a("    if (decoded != null) {")
a("      _sessions.remove(hdr.messageId);")
a("      AppLogging.tak(")
a("        'Fountain: decoded message ${hdr.messageId.toRadixString(16)} '")
a("        'from ${session.receivedSource.length} source + ${session.paritySymbols.length} parity symbols '")
a("        '(${decoded.length} bytes recovered)',")
a("      );")
a("    }")
a("")
a("    return decoded;")
a("  }")
a("")
a("  /// Returns IDs of timed-out sessions that were evicted.")
a("  List<int> evictExpired() {")
a("    return _evictExpired();")
a("  }")
a("")
a("  /// Number of active decode sessions.")
a("  int get activeSessionCount => _sessions.length;")
a("")
a("  List<int> _evictExpired() {")
a("    final now = DateTime.now();")
a("    final expired = <int>[];")
a("    _sessions.removeWhere((id, session) {")
a("      final isExpired = now.difference(session.created) > timeout;")
a("      if (isExpired) {")
a("        expired.add(id);")
a("        AppLogging.tak(")
a("          'Fountain: decode timeout for message ${id.toRadixString(16)} '")
a("          'after ${timeout.inSeconds}s '")
a("          '(received ${session.receivedSource.length}/${session.k} symbols)',")
a("        );")
a("      }")
a("      return isExpired;")
a("    });")
a("    return expired;")
a("  }")
a("")
a("  void _evictOldestIfFull() {")
a("    while (_sessions.length >= maxSessions) {")
a("      final oldest = _sessions.entries.reduce(")
a("        (a, b) => a.value.created.isBefore(b.value.created) ? a : b,")
a("      );")
a("      _sessions.remove(oldest.key);")
a("      AppLogging.tak(")
a("        'Fountain: evicted oldest session ${oldest.key.toRadixString(16)} (max $maxSessions sessions)',")
a("      );")
a("    }")
a("  }")
a("")
a("  /// Attempts to decode the session using available symbols.")
a("  ///")
a("  /// Uses iterative peeling: resolve degree-1 parity symbols first,")
a("  /// then propagate to resolve higher-degree symbols.")
a("  Uint8List? _tryDecode(_DecodeSession session) {")
a("    if (session.receivedSource.length == session.k) {")
a("      return _assemblePayload(session);")
a("    }")
a("")
a("    // Iterative peeling decoder.")
a("    var progress = true;")
a("    while (progress) {")
a("      progress = false;")
a("      for (final parity in List.of(session.paritySymbols)) {")
a("        final hdr = parity.header;")
a("        if (hdr.seed == 0) continue;")
a("")
a("        final degree = FountainEncoder._degree(hdr.seed, session.k);")
a("        final indices = FountainEncoder._selectIndices(hdr.seed, session.k, degree);")
a("")
a("        // Find unknown indices.")
a("        final unknown = indices.where((i) => !session.receivedSource.containsKey(i)).toList();")
a("")
a("        if (unknown.length == 1) {")
a("          // Can resolve: XOR known sources with parity to get missing.")
a("          final resolved = Uint8List(session.symbolSize);")
a("          resolved.setAll(0, parity.payload);")
a("          for (final i in indices) {")
a("            if (session.receivedSource.containsKey(i)) {")
a("              for (var b = 0; b < session.symbolSize; b++) {")
a("                resolved[b] ^= session.receivedSource[i]![b];")
a("              }")
a("            }")
a("          }")
a("          session.receivedSource[unknown.first] = resolved;")
a("          session.paritySymbols.remove(parity);")
a("          progress = true;")
a("        } else if (unknown.isEmpty) {")
a("          // Already resolved, discard parity.")
a("          session.paritySymbols.remove(parity);")
a("        }")
a("      }")
a("    }")
a("")
a("    if (session.receivedSource.length == session.k) {")
a("      return _assemblePayload(session);")
a("    }")
a("")
a("    return null;")
a("  }")
a("")
a("  Uint8List _assemblePayload(_DecodeSession session) {")
a("    final result = Uint8List(session.k * session.symbolSize);")
a("    for (var i = 0; i < session.k; i++) {")
a("      result.setAll(i * session.symbolSize, session.receivedSource[i]!);")
a("    }")
a("    return result;")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
