#!/usr/bin/env python3
"""Generate tak_protocol_handler.dart — TAK Protocol v1 frame parser."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/tak_protocol_handler.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:typed_data';")
a("")
a("import '../../core/logging.dart';")
a("")
a("/// TAK Protocol v1 frame types.")
a("enum TakFrameType {")
a("  /// XML CoT event.")
a("  xmlCot(0),")
a("")
a("  /// Protobuf CoT event.")
a("  protobufCot(1),")
a("")
a("  /// Protocol negotiation message.")
a("  negotiation(2),")
a("")
a("  /// Keepalive ping/pong.")
a("  keepalive(3);")
a("")
a("  const TakFrameType(this.value);")
a("  final int value;")
a("")
a("  static TakFrameType? fromValue(int v) {")
a("    for (final t in values) {")
a("      if (t.value == v) return t;")
a("    }")
a("    return null;")
a("  }")
a("}")
a("")
a("/// A parsed TAK Protocol v1 frame.")
a("class TakFrame {")
a("  final TakFrameType type;")
a("  final Uint8List payload;")
a("")
a("  const TakFrame({required this.type, required this.payload});")
a("}")
a("")
a("/// Parses and builds TAK Protocol v1 wire frames.")
a("///")
a("/// Wire format: `[0xBF] [type:1] [varint length] [payload]`")
a("///")
a("/// Handles TCP stream reassembly via internal buffer.")
a("class TakProtocolHandler {")
a("  /// Magic byte identifying a TAK Protocol v1 frame.")
a("  static const int magic = 0xBF;")
a("")
a("  /// Keepalive interval.")
a("  static const Duration keepaliveInterval = Duration(seconds: 30);")
a("")
a("  /// Keepalive response timeout.")
a("  static const Duration keepaliveTimeout = Duration(seconds: 10);")
a("")
a("  /// Maximum consecutive missed keepalive pongs before disconnect.")
a("  static const int maxMissedKeepalives = 3;")
a("")
a("  /// Maximum frame payload size (64 KB).")
a("  static const int maxPayloadSize = 65536;")
a("")
a("  final _buffer = BytesBuilder(copy: false);")
a("")
a("  /// Feeds raw bytes from the TCP stream and returns any complete frames.")
a("  List<TakFrame> feedBytes(Uint8List data) {")
a("    _buffer.add(data);")
a("    final buffered = _buffer.takeBytes();")
a("    final frames = <TakFrame>[];")
a("    var offset = 0;")
a("")
a("    while (offset < buffered.length) {")
a("      // Need at least magic + type + 1 varint byte = 3 bytes.")
a("      if (offset + 3 > buffered.length) break;")
a("")
a("      if (buffered[offset] != magic) {")
a("        AppLogging.tak(")
a("          'Protocol: invalid magic byte 0x${buffered[offset].toRadixString(16)} at offset $offset, skipping',")
a("        );")
a("        offset++;")
a("        continue;")
a("      }")
a("")
a("      final typeValue = buffered[offset + 1];")
a("      final frameType = TakFrameType.fromValue(typeValue);")
a("      if (frameType == null) {")
a("        AppLogging.tak(")
a("          'Protocol: unknown frame type $typeValue, skipping',")
a("        );")
a("        offset += 2;")
a("        continue;")
a("      }")
a("")
a("      // Parse varint length.")
a("      final varintResult = _readVarint(buffered, offset + 2);")
a("      if (varintResult == null) break; // Need more bytes for varint.")
a("")
a("      final payloadLength = varintResult.value;")
a("      final headerEnd = varintResult.nextOffset;")
a("")
a("      if (payloadLength > maxPayloadSize) {")
a("        AppLogging.tak(")
a("          'Protocol: payload too large ($payloadLength > $maxPayloadSize), discarding frame',")
a("        );")
a("        offset = headerEnd;")
a("        continue;")
a("      }")
a("")
a("      if (headerEnd + payloadLength > buffered.length) break; // Incomplete payload.")
a("")
a("      final payload = Uint8List.fromList(")
a("        buffered.sublist(headerEnd, headerEnd + payloadLength),")
a("      );")
a("      frames.add(TakFrame(type: frameType, payload: payload));")
a("      offset = headerEnd + payloadLength;")
a("    }")
a("")
a("    // Put unconsumed bytes back in the buffer.")
a("    if (offset < buffered.length) {")
a("      _buffer.add(buffered.sublist(offset));")
a("    }")
a("")
a("    return frames;")
a("  }")
a("")
a("  /// Serializes a [TakFrame] to wire bytes.")
a("  static Uint8List buildFrame(TakFrameType type, Uint8List payload) {")
a("    final varint = _encodeVarint(payload.length);")
a("    final result = Uint8List(2 + varint.length + payload.length);")
a("    result[0] = magic;")
a("    result[1] = type.value;")
a("    result.setAll(2, varint);")
a("    result.setAll(2 + varint.length, payload);")
a("    return result;")
a("  }")
a("")
a("  /// Builds a negotiation frame advertising protocol version 1.")
a("  static Uint8List buildNegotiation() {")
a("    // Negotiation payload: protocol version as single byte.")
a("    final payload = Uint8List.fromList([1]); // TAK Protocol v1")
a("    return buildFrame(TakFrameType.negotiation, payload);")
a("  }")
a("")
a("  /// Builds a keepalive ping frame.")
a("  static Uint8List buildKeepalivePing() {")
a("    return buildFrame(TakFrameType.keepalive, Uint8List(0));")
a("  }")
a("")
a("  /// Builds a keepalive pong frame (same as ping for TAK Protocol v1).")
a("  static Uint8List buildKeepalivePong() {")
a("    return buildFrame(TakFrameType.keepalive, Uint8List(0));")
a("  }")
a("")
a("  /// Builds a frame for an XML CoT event.")
a("  static Uint8List buildXmlCotFrame(String cotXml) {")
a("    return buildFrame(")
a("      TakFrameType.xmlCot,")
a("      Uint8List.fromList(cotXml.codeUnits),")
a("    );")
a("  }")
a("")
a("  /// Builds a frame for a protobuf CoT event.")
a("  static Uint8List buildProtobufCotFrame(Uint8List protobufBytes) {")
a("    return buildFrame(TakFrameType.protobufCot, protobufBytes);")
a("  }")
a("")
a("  /// Resets the internal buffer (e.g., on connection close).")
a("  void reset() {")
a("    _buffer.clear();")
a("  }")
a("")
a("  // --- Varint helpers ---")
a("")
a("  static ({int value, int nextOffset})? _readVarint(")
a("    Uint8List data,")
a("    int offset,")
a("  ) {")
a("    var value = 0;")
a("    var shift = 0;")
a("    var pos = offset;")
a("")
a("    while (pos < data.length) {")
a("      final byte = data[pos];")
a("      value |= (byte & 0x7F) << shift;")
a("      pos++;")
a("      if ((byte & 0x80) == 0) {")
a("        return (value: value, nextOffset: pos);")
a("      }")
a("      shift += 7;")
a("      if (shift > 28) return null; // Varint too long.")
a("    }")
a("")
a("    return null; // Incomplete varint.")
a("  }")
a("")
a("  static Uint8List _encodeVarint(int value) {")
a("    if (value < 0) return Uint8List.fromList([0]);")
a("    final bytes = <int>[];")
a("    var v = value;")
a("    do {")
a("      var byte = v & 0x7F;")
a("      v >>= 7;")
a("      if (v > 0) byte |= 0x80;")
a("      bytes.add(byte);")
a("    } while (v > 0);")
a("    return Uint8List.fromList(bytes);")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
