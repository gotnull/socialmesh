#!/usr/bin/env python3
"""Generate tak_bridge_providers.dart — Riverpod providers for TAK bridge."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/providers/tak_bridge_providers.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:async';")
a("")
a("import 'package:flutter_riverpod/flutter_riverpod.dart';")
a("")
a("import '../../../core/constants.dart';")
a("import '../../../core/logging.dart';")
a("import '../certificate_manager.dart';")
a("import '../geochat_bridge.dart';")
a("import '../identity_registry.dart';")
a("import '../tak_mesh_bridge.dart';")
a("import '../tak_server.dart';")
a("")
a("/// Whether the TAK Mesh Bridge feature flag is enabled.")
a("final isTakMeshBridgeEnabledProvider = Provider<bool>((ref) {")
a("  return AppFeatureFlags.isTakMeshBridgeEnabled;")
a("});")
a("")
a("/// TAK certificate manager (singleton).")
a("final takCertManagerProvider = Provider<TakCertificateManager>((ref) {")
a("  AppLogging.tak('Creating TakCertificateManager provider');")
a("  final manager = TakCertificateManager();")
a("  return manager;")
a("});")
a("")
a("/// TAK identity registry (singleton).")
a("final takIdentityRegistryProvider = Provider<TakIdentityRegistry>((ref) {")
a("  AppLogging.tak('Creating TakIdentityRegistry provider');")
a("  return TakIdentityRegistry();")
a("});")
a("")
a("/// TAK server instance.")
a("final takServerProvider = Provider<TakServer>((ref) {")
a("  final certManager = ref.watch(takCertManagerProvider);")
a("  AppLogging.tak('Creating TakServer provider');")
a("  final server = TakServer(certManager);")
a("  ref.onDispose(() {")
a("    AppLogging.tak('Disposing TakServer provider');")
a("    server.dispose();")
a("  });")
a("  return server;")
a("});")
a("")
a("/// TAK mesh bridge instance.")
a("final takMeshBridgeProvider = Provider<TakMeshBridge>((ref) {")
a("  final server = ref.watch(takServerProvider);")
a("  AppLogging.tak('Creating TakMeshBridge provider');")
a("  final bridge = TakMeshBridge(")
a("    server: server,")
a("    meshSend: (payload, {required int portnum, int? destination}) async {")
a("      // Placeholder — will be wired to ProtocolService in integration.")
a("      AppLogging.tak(")
a("        'Bridge meshSend: ${payload.length} bytes on portnum $portnum',")
a("      );")
a("    },")
a("  );")
a("  ref.onDispose(() {")
a("    AppLogging.tak('Disposing TakMeshBridge provider');")
a("    bridge.dispose();")
a("  });")
a("  return bridge;")
a("});")
a("")
a("/// TAK GeoChat bridge instance.")
a("final takGeoChatBridgeProvider = Provider<GeoChatBridge>((ref) {")
a("  final registry = ref.watch(takIdentityRegistryProvider);")
a("  AppLogging.tak('Creating GeoChatBridge provider');")
a("  return GeoChatBridge(")
a("    meshSend: (text, {int channelIndex = 0, int? destination}) async {")
a("      // Placeholder — will be wired to ProtocolService in integration.")
a("      AppLogging.tak(")
a("        'GeoChat meshSend: \"$text\" on channel $channelIndex',")
a("      );")
a("      return 0;")
a("    },")
a("    callsignResolver: (callsign) {")
a("      final identity = registry.lookupByCallsign(callsign);")
a("      return identity?.nodeNum;")
a("    },")
a("  );")
a("});")
a("")
a("/// Snapshot of bridge operational status.")
a("class TakBridgeStatus {")
a("  final bool isRunning;")
a("  final int connectedClientCount;")
a("  final int packetsInbound;")
a("  final int packetsOutbound;")
a("  final DateTime? lastActivity;")
a("")
a("  const TakBridgeStatus({")
a("    this.isRunning = false,")
a("    this.connectedClientCount = 0,")
a("    this.packetsInbound = 0,")
a("    this.packetsOutbound = 0,")
a("    this.lastActivity,")
a("  });")
a("}")
a("")
a("/// Bridge status notifier — refreshes on a timer stream.")
a("class TakBridgeStatusNotifier extends Notifier<TakBridgeStatus> {")
a("  Timer? _timer;")
a("")
a("  @override")
a("  TakBridgeStatus build() {")
a("    ref.onDispose(() => _timer?.cancel());")
a("")
a("    // Poll status every 5 seconds.")
a("    _timer = Timer.periodic(const Duration(seconds: 5), (_) => _refresh());")
a("")
a("    return _snapshot();")
a("  }")
a("")
a("  void _refresh() => state = _snapshot();")
a("")
a("  TakBridgeStatus _snapshot() {")
a("    final bridge = ref.read(takMeshBridgeProvider);")
a("    final server = ref.read(takServerProvider);")
a("    return TakBridgeStatus(")
a("      isRunning: bridge.isRunning,")
a("      connectedClientCount: server.clientCount,")
a("      packetsInbound: bridge.packetsInbound,")
a("      packetsOutbound: bridge.packetsOutbound,")
a("    );")
a("  }")
a("}")
a("")
a("final takBridgeStatusProvider =")
a("    NotifierProvider<TakBridgeStatusNotifier, TakBridgeStatus>(")
a("  TakBridgeStatusNotifier.new,")
a(");")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
