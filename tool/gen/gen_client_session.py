#!/usr/bin/env python3
"""Generate tak_client_session.dart."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/tak_client_session.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:async';")
a("import 'dart:io';")
a("import 'dart:typed_data';")
a("")
a("import '../../core/logging.dart';")
a("import 'tak_protocol_handler.dart';")
a("")
a("/// Connection state of a TAK client session.")
a("enum TakSessionState {")
a("  /// Connected, awaiting protocol negotiation.")
a("  pendingNegotiation,")
a("")
a("  /// Negotiation complete, operational.")
a("  authenticated,")
a("")
a("  /// Session closed.")
a("  closed,")
a("}")
a("")
a("/// Represents a single ATAK/iTAK client connected to [TakServer].")
a("class TakClientSession {")
a("  final SecureSocket socket;")
a("  final TakProtocolHandler protocolHandler = TakProtocolHandler();")
a("  final DateTime connectedAt = DateTime.now();")
a("  DateTime lastActivityAt;")
a("  String callsign;")
a("  String uid;")
a("  TakSessionState state;")
a("  int missedKeepalives;")
a("  StreamSubscription<Uint8List>? _subscription;")
a("  Timer? _keepaliveTimer;")
a("  Timer? _keepaliveTimeoutTimer;")
a("")
a("  /// Controller for CoT events received from this client.")
a("  final _cotController = StreamController<String>.broadcast();")
a("")
a("  /// Controller for session lifecycle events.")
a("  final _eventController = StreamController<TakSessionEvent>.broadcast();")
a("")
a("  TakClientSession(this.socket)")
a("      : lastActivityAt = DateTime.now(),")
a("        callsign = '',")
a("        uid = '',")
a("        state = TakSessionState.pendingNegotiation,")
a("        missedKeepalives = 0;")
a("")
a("  /// Stream of CoT XML events received from this client.")
a("  Stream<String> get cotEvents => _cotController.stream;")
a("")
a("  /// Stream of session lifecycle events.")
a("  Stream<TakSessionEvent> get events => _eventController.stream;")
a("")
a("  /// Remote address string.")
a("  String get remoteAddress => '${socket.remoteAddress.address}:${socket.remotePort}';")
a("")
a("  /// Connection duration.")
a("  Duration get connectionDuration => DateTime.now().difference(connectedAt);")
a("")
a("  /// Starts listening on the socket and initiates negotiation.")
a("  void start() {")
a("    _subscription = socket.listen(")
a("      _onData,")
a("      onError: (Object error) {")
a("        AppLogging.tak('Client $remoteAddress error: $error');")
a("        close();")
a("      },")
a("      onDone: close,")
a("    );")
a("")
a("    // Send server negotiation.")
a("    _sendRaw(TakProtocolHandler.buildNegotiation());")
a("    AppLogging.tak('Client connected: $remoteAddress (pending negotiation)');")
a("  }")
a("")
a("  /// Sends a CoT XML event to this client.")
a("  void sendCot(String cotXml) {")
a("    if (state == TakSessionState.closed) return;")
a("    final frame = TakProtocolHandler.buildXmlCotFrame(cotXml);")
a("    _sendRaw(frame);")
a("  }")
a("")
a("  /// Closes the session and releases resources.")
a("  void close() {")
a("    if (state == TakSessionState.closed) return;")
a("    state = TakSessionState.closed;")
a("    _keepaliveTimer?.cancel();")
a("    _keepaliveTimeoutTimer?.cancel();")
a("    _subscription?.cancel();")
a("    socket.destroy();")
a("    _eventController.add(TakSessionEvent.disconnected);")
a("    _cotController.close();")
a("    _eventController.close();")
a("    AppLogging.tak(")
a("      'Client disconnected: ${callsign.isNotEmpty ? callsign : remoteAddress}',")
a("    );")
a("  }")
a("")
a("  void _onData(Uint8List data) {")
a("    lastActivityAt = DateTime.now();")
a("    final frames = protocolHandler.feedBytes(data);")
a("")
a("    for (final frame in frames) {")
a("      switch (frame.type) {")
a("        case TakFrameType.negotiation:")
a("          _handleNegotiation(frame);")
a("        case TakFrameType.xmlCot:")
a("          _handleXmlCot(frame);")
a("        case TakFrameType.protobufCot:")
a("          _handleProtobufCot(frame);")
a("        case TakFrameType.keepalive:")
a("          _handleKeepalive();")
a("      }")
a("    }")
a("  }")
a("")
a("  void _handleNegotiation(TakFrame frame) {")
a("    state = TakSessionState.authenticated;")
a("    // Extract version from negotiation payload.")
a("    final version = frame.payload.isNotEmpty ? frame.payload[0] : 0;")
a("    AppLogging.tak(")
a("      'Protocol negotiation: client=TAKv$version, server=TAKv1, agreed=TAKv1',")
a("    );")
a("    _eventController.add(TakSessionEvent.authenticated);")
a("    _startKeepalive();")
a("  }")
a("")
a("  void _handleXmlCot(TakFrame frame) {")
a("    final xml = String.fromCharCodes(frame.payload);")
a("    _cotController.add(xml);")
a("  }")
a("")
a("  void _handleProtobufCot(TakFrame frame) {")
a("    // For protobuf CoT, we'll handle it at the bridge level.")
a("    // Emit as base64 or pass raw bytes through a separate channel.")
a("    AppLogging.tak(")
a("      'Received protobuf CoT from ${callsign.isNotEmpty ? callsign : remoteAddress} (${frame.payload.length} bytes)',")
a("    );")
a("  }")
a("")
a("  void _handleKeepalive() {")
a("    missedKeepalives = 0;")
a("    _keepaliveTimeoutTimer?.cancel();")
a("  }")
a("")
a("  void _startKeepalive() {")
a("    _keepaliveTimer = Timer.periodic(")
a("      TakProtocolHandler.keepaliveInterval,")
a("      (_) => _sendKeepalivePing(),")
a("    );")
a("  }")
a("")
a("  void _sendKeepalivePing() {")
a("    if (state == TakSessionState.closed) return;")
a("")
a("    _sendRaw(TakProtocolHandler.buildKeepalivePing());")
a("")
a("    _keepaliveTimeoutTimer?.cancel();")
a("    _keepaliveTimeoutTimer = Timer(TakProtocolHandler.keepaliveTimeout, () {")
a("      missedKeepalives++;")
a("      if (missedKeepalives >= TakProtocolHandler.maxMissedKeepalives) {")
a("        AppLogging.tak(")
a("          'Client ${callsign.isNotEmpty ? callsign : remoteAddress} missed $missedKeepalives keepalives, closing session',")
a("        );")
a("        close();")
a("      }")
a("    });")
a("  }")
a("")
a("  void _sendRaw(Uint8List data) {")
a("    if (state == TakSessionState.closed) return;")
a("    try {")
a("      socket.add(data);")
a("    } on SocketException {")
a("      close();")
a("    }")
a("  }")
a("}")
a("")
a("/// Events emitted by a [TakClientSession].")
a("enum TakSessionEvent {")
a("  authenticated,")
a("  disconnected,")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
