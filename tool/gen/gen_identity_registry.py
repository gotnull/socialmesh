#!/usr/bin/env python3
"""Generate identity_registry.dart — callsign-nodeNum identity mapping."""
import os

OUT = "/Users/fulvio/development/socialmesh/lib/services/tak/identity_registry.dart"
os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
a = lines.append

a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import '../../core/logging.dart';")
a("")
a("/// A TAK ↔ Meshtastic identity mapping entry.")
a("class TakIdentity {")
a("  /// Meshtastic node number (0 for TAK-only clients).")
a("  final int nodeNum;")
a("")
a("  /// TAK UID (e.g., 'MESHTASTIC-1A2B3C4D' or 'ANDROID-abc123').")
a("  final String takUid;")
a("")
a("  /// Callsign or display name.")
a("  final String callsign;")
a("")
a("  /// Manual callsign override (takes precedence over [callsign]).")
a("  final String? overrideCallsign;")
a("")
a("  /// First seen timestamp (ms since epoch).")
a("  final int firstSeenMs;")
a("")
a("  /// Last seen timestamp (ms since epoch).")
a("  final int lastSeenMs;")
a("")
a("  TakIdentity({")
a("    required this.nodeNum,")
a("    required this.takUid,")
a("    required this.callsign,")
a("    this.overrideCallsign,")
a("    required this.firstSeenMs,")
a("    required this.lastSeenMs,")
a("  });")
a("")
a("  /// The effective display callsign (override if set, else callsign).")
a("  String get displayCallsign => overrideCallsign ?? callsign;")
a("")
a("  /// Whether this identity is for a Meshtastic mesh node.")
a("  bool get isMeshNode => nodeNum != 0;")
a("")
a("  /// Returns a copy with updated fields.")
a("  TakIdentity copyWith({")
a("    int? nodeNum,")
a("    String? takUid,")
a("    String? callsign,")
a("    String? overrideCallsign,")
a("    int? firstSeenMs,")
a("    int? lastSeenMs,")
a("  }) {")
a("    return TakIdentity(")
a("      nodeNum: nodeNum ?? this.nodeNum,")
a("      takUid: takUid ?? this.takUid,")
a("      callsign: callsign ?? this.callsign,")
a("      overrideCallsign: overrideCallsign ?? this.overrideCallsign,")
a("      firstSeenMs: firstSeenMs ?? this.firstSeenMs,")
a("      lastSeenMs: lastSeenMs ?? this.lastSeenMs,")
a("    );")
a("  }")
a("")
a("  /// Converts to a database row map.")
a("  Map<String, Object?> toMap() => {")
a("    'node_num': nodeNum,")
a("    'tak_uid': takUid,")
a("    'callsign': callsign,")
a("    'override_callsign': overrideCallsign,")
a("    'first_seen_ms': firstSeenMs,")
a("    'last_seen_ms': lastSeenMs,")
a("  };")
a("")
a("  /// Creates from a database row map.")
a("  factory TakIdentity.fromMap(Map<String, Object?> map) => TakIdentity(")
a("    nodeNum: map['node_num'] as int? ?? 0,")
a("    takUid: map['tak_uid'] as String? ?? '',")
a("    callsign: map['callsign'] as String? ?? '',")
a("    overrideCallsign: map['override_callsign'] as String?,")
a("    firstSeenMs: map['first_seen_ms'] as int? ?? 0,")
a("    lastSeenMs: map['last_seen_ms'] as int? ?? 0,")
a("  );")
a("")
a("  @override")
a("  bool operator ==(Object other) =>")
a("      identical(this, other) ||")
a("      other is TakIdentity &&")
a("          nodeNum == other.nodeNum &&")
a("          takUid == other.takUid &&")
a("          callsign == other.callsign &&")
a("          overrideCallsign == other.overrideCallsign;")
a("")
a("  @override")
a("  int get hashCode => Object.hash(nodeNum, takUid, callsign, overrideCallsign);")
a("")
a("  @override")
a("  String toString() => 'TakIdentity(nodeNum=$nodeNum, uid=$takUid, callsign=$displayCallsign)';")
a("}")
a("")
a("/// Callback to persist identity data.")
a("typedef IdentityPersistCallback = Future<void> Function(TakIdentity identity);")
a("")
a("/// Callback to load all persisted identities.")
a("typedef IdentityLoadCallback = Future<List<TakIdentity>> Function();")
a("")
a("/// Bidirectional identity registry for TAK ↔ Meshtastic mapping.")
a("///")
a("/// Maintains in-memory lookup maps with optional persistence callbacks.")
a("class TakIdentityRegistry {")
a("  final IdentityPersistCallback? _persist;")
a("  final IdentityLoadCallback? _load;")
a("")
a("  /// nodeNum -> TakIdentity")
a("  final _byNodeNum = <int, TakIdentity>{};")
a("")
a("  /// takUid -> TakIdentity")
a("  final _byTakUid = <String, TakIdentity>{};")
a("")
a("  /// callsign (lowercased) -> TakIdentity")
a("  final _byCallsign = <String, TakIdentity>{};")
a("")
a("  TakIdentityRegistry({")
a("    IdentityPersistCallback? persist,")
a("    IdentityLoadCallback? load,")
a("  })  : _persist = persist,")
a("        _load = load;")
a("")
a("  /// Loads identities from persistence.")
a("  Future<void> loadFromStorage() async {")
a("    if (_load == null) return;")
a("    final identities = await _load();")
a("    for (final identity in identities) {")
a("      _index(identity);")
a("    }")
a("    AppLogging.tak(")
a("      'Identity: registry loaded ${identities.length} identities from database',")
a("    );")
a("  }")
a("")
a("  /// Registers (or updates) a Meshtastic mesh node.")
a("  Future<void> registerMeshNode(int nodeNum, String longName, String shortName) async {")
a("    final nodeHex = nodeNum.toRadixString(16).toUpperCase().padLeft(8, '0');")
a("    final takUid = 'MESHTASTIC-$nodeHex';")
a("    final callsign = longName.isNotEmpty ? longName : shortName;")
a("    final now = DateTime.now().millisecondsSinceEpoch;")
a("")
a("    final existing = _byNodeNum[nodeNum];")
a("    final identity = TakIdentity(")
a("      nodeNum: nodeNum,")
a("      takUid: takUid,")
a("      callsign: callsign,")
a("      overrideCallsign: existing?.overrideCallsign,")
a("      firstSeenMs: existing?.firstSeenMs ?? now,")
a("      lastSeenMs: now,")
a("    );")
a("")
a("    _index(identity);")
a("    await _persist?.call(identity);")
a("")
a("    AppLogging.tak(")
a("      \"Identity: registered mesh node 0x$nodeHex -> $takUid (callsign='$callsign')\",")
a("    );")
a("  }")
a("")
a("  /// Registers (or updates) a TAK client.")
a("  Future<void> registerTakClient(String uid, String callsign) async {")
a("    final now = DateTime.now().millisecondsSinceEpoch;")
a("")
a("    final existing = _byTakUid[uid];")
a("    final identity = TakIdentity(")
a("      nodeNum: 0, // TAK clients have no mesh node number.")
a("      takUid: uid,")
a("      callsign: callsign,")
a("      overrideCallsign: existing?.overrideCallsign,")
a("      firstSeenMs: existing?.firstSeenMs ?? now,")
a("      lastSeenMs: now,")
a("    );")
a("")
a("    _index(identity);")
a("    await _persist?.call(identity);")
a("")
a("    AppLogging.tak(")
a("      \"Identity: registered TAK client $uid -> callsign='$callsign'\",")
a("    );")
a("  }")
a("")
a("  /// Looks up identity by Meshtastic node number.")
a("  TakIdentity? lookupByNodeNum(int nodeNum) => _byNodeNum[nodeNum];")
a("")
a("  /// Looks up identity by TAK UID.")
a("  TakIdentity? lookupByTakUid(String uid) => _byTakUid[uid];")
a("")
a("  /// Looks up identity by callsign (case-insensitive).")
a("  TakIdentity? lookupByCallsign(String callsign) =>")
a("      _byCallsign[callsign.toLowerCase()];")
a("")
a("  /// Sets a manual callsign override for a mesh node.")
a("  Future<void> setCallsignOverride(int nodeNum, String customCallsign) async {")
a("    final existing = _byNodeNum[nodeNum];")
a("    if (existing == null) return;")
a("")
a("    final oldCallsign = existing.displayCallsign;")
a("    final updated = existing.copyWith(overrideCallsign: customCallsign);")
a("    _index(updated);")
a("    await _persist?.call(updated);")
a("")
a("    AppLogging.tak(")
a("      \"Identity: callsign override for 0x${nodeNum.toRadixString(16).toUpperCase().padLeft(8, '0')}: '$oldCallsign' -> '$customCallsign'\",")
a("    );")
a("  }")
a("")
a("  /// All registered identities.")
a("  List<TakIdentity> get allIdentities => _byTakUid.values.toList();")
a("")
a("  /// Count of registered mesh nodes.")
a("  int get meshNodeCount => _byNodeNum.values.where((i) => i.isMeshNode).length;")
a("")
a("  /// Count of registered TAK clients.")
a("  int get takClientCount => _byTakUid.values.where((i) => !i.isMeshNode).length;")
a("")
a("  /// Clears all identities from memory.")
a("  void clear() {")
a("    _byNodeNum.clear();")
a("    _byTakUid.clear();")
a("    _byCallsign.clear();")
a("  }")
a("")
a("  // --- Internal ---")
a("")
a("  void _index(TakIdentity identity) {")
a("    // Remove old callsign index if the callsign changed.")
a("    final oldByUid = _byTakUid[identity.takUid];")
a("    if (oldByUid != null) {")
a("      _byCallsign.remove(oldByUid.displayCallsign.toLowerCase());")
a("    }")
a("")
a("    if (identity.nodeNum != 0) {")
a("      _byNodeNum[identity.nodeNum] = identity;")
a("    }")
a("    _byTakUid[identity.takUid] = identity;")
a("    _byCallsign[identity.displayCallsign.toLowerCase()] = identity;")
a("  }")
a("}")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT}")
