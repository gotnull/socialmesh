# --- cot_compressor.dart ---
OUT1 = "/Users/fulvio/development/socialmesh/lib/services/tak/cot_compressor.dart"
lines = []
a = lines.append
a("// SPDX-License-Identifier: GPL-3.0-or-later")
a("// SPDX-FileCopyrightText: 2025-2026 gotnull (developer@socialmesh.app)")
a("import 'dart:io';")
a("import 'dart:typed_data';")
a("")
a("import '../../core/logging.dart';")
a("")
a("/// Compresses and decompresses CoT payloads using zlib (deflate).")
a("///")
a("/// Used by [TakMeshBridge] to reduce TAKPacket payload sizes for mesh")
a("/// transport. Meshtastic has a 237-byte payload limit.")
a("abstract final class CotCompressor {")
a("  /// Minimum payload size (bytes) before compression is applied.")
a("  static const int compressionThreshold = 100;")
a("")
a("  /// Maximum allowed payload size for mesh transmission.")
a("  static const int maxMeshPayload = 237;")
a("")
a("  /// Compresses [data] with zlib.")
a("  ///")
a("  /// Returns `null` if:")
a("  /// - [data] is shorter than [compressionThreshold]")
a("  /// - compressed output is >= original size (negative ratio)")
a("  /// - compressed output exceeds [maxMeshPayload]")
a("  static Uint8List? compress(Uint8List data) {")
a("    if (data.length < compressionThreshold) {")
a("      AppLogging.tak(")
a("        'Compression: skipped for ${data.length} byte payload (below $compressionThreshold byte threshold)',")
a("      );")
a("      return null;")
a("    }")
a("")
a("    final compressed = Uint8List.fromList(zlib.encode(data));")
a("")
a("    if (compressed.length >= data.length) {")
a("      AppLogging.tak(")
a("        'Compression: skipped — compressed ${compressed.length} >= original ${data.length}',")
a("      );")
a("      return null;")
a("    }")
a("")
a("    if (compressed.length > maxMeshPayload) {")
a("      AppLogging.tak(")
a("        'Compression: ${data.length} bytes -> ${compressed.length} bytes, still exceeds $maxMeshPayload byte limit, packet rejected',")
a("      );")
a("      return null;")
a("    }")
a("")
a("    final ratio = compressed.length / data.length;")
a("    final saved = data.length - compressed.length;")
a("    AppLogging.tak(")
a("      'Compression: ${data.length} bytes -> ${compressed.length} bytes (ratio ${ratio.toStringAsFixed(2)}, saved $saved bytes)',")
a("    );")
a("    return compressed;")
a("  }")
a("")
a("  /// Decompresses zlib-compressed [data].")
a("  static Uint8List decompress(Uint8List data) {")
a("    return Uint8List.fromList(zlib.decode(data));")
a("  }")
a("}")
with open(OUT1, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"OK: {len(lines)} lines -> {OUT1}")

