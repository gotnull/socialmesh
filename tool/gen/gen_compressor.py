a("")
a("void main() {")
a("  group('CotCompressor', () {")
a("    test('compress/decompress round-trip preserves data', () {")
a("      // Create a payload large enough to compress (>100 bytes)")
a("      final original = Uint8List.fromList(")
a("        List.generate(200, (i) => i % 10), // repetitive = compressible")
a("      );")
a("      final compressed = CotCompressor.compress(original);")
a("      expect(compressed, isNotNull);")
a("      final decompressed = CotCompressor.decompress(compressed!);")
a("      expect(decompressed, original);")
a("    });")
a("")
a("    test('skips payload below threshold', () {")
a("      final small = Uint8List(50);")
a("      expect(CotCompressor.compress(small), isNull);")
a("    });")
a("")
a("    test('skips payload at exactly threshold', () {")
a("      final exact = Uint8List(CotCompressor.compressionThreshold - 1);")
a("      expect(CotCompressor.compress(exact), isNull);")
a("    });")
a("")
a("    test('skips if compressed >= original (random data)', () {")
a("      // Random data does not compress well")
a("      final random = Uint8List.fromList(")
a("        List.generate(120, (i) => (i * 37 + 13) % 256),")
a("      );")
a("      // May or may not compress; if it doesn't, returns null")
a("      final result = CotCompressor.compress(random);")
a("      if (result != null) {")
a("        expect(result.length, lessThan(random.length));")
a("      }")
a("    });")
a("")
a("    test('compresses repetitive data effectively', () {")
a("      final repetitive = Uint8List.fromList(")
a("        List.generate(200, (_) => 0x41), // 'AAAA...'")
a("      );")
a("      final compressed = CotCompressor.compress(repetitive);")
a("      expect(compressed, isNotNull);")
a("      expect(compressed!.length, lessThan(repetitive.length));")
a("    });")
a("")
a("    test('rejects if compressed still exceeds max mesh payload', () {")
a("      // Create data that's large but compresses to just above limit")
a("      // 500 bytes of pseudo-random data unlikely to compress below 237")
a("      final large = Uint8List.fromList(")
a("        List.generate(500, (i) => (i * 53 + 7) % 256),")
a("      );")
a("      final result = CotCompressor.compress(large);")
a("      // If compressed is still > 237, should return null")
a("      if (result != null) {")
a("        expect(result.length, lessThanOrEqualTo(CotCompressor.maxMeshPayload));")
a("      }")
a("    });")
a("")
a("    test('decompress handles valid zlib data', () {")
a("      final data = Uint8List.fromList(List.generate(150, (i) => i % 5));")
a("      final compressed = CotCompressor.compress(data)!;")
a("      final result = CotCompressor.decompress(compressed);")
a("      expect(result, data);")
a("    });")
a("  });")
a("}")
